#!/usr/bin/env bash
# Behind Cloudflare, every request reaches nginx from a Cloudflare address.
# Without this, rate limits count all visitors behind one Cloudflare edge as a
# single client (so real students can block each other), and the API, request
# logs and panel audit log record Cloudflare's IP instead of the visitor's.
#
# Trusts CF-Connecting-IP only from Cloudflare's published ranges, so nobody
# else can fake it. Safe to rerun; rerun now and then to pick up new ranges.
set -Eeuo pipefail

[[ ${EUID} -eq 0 ]] || { echo "Run as root: sudo bash $0" >&2; exit 1; }
TARGET="/etc/nginx/conf.d/cloudflare-realip.conf"

v4="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)"
[[ $(grep -c . <<<"$v4") -ge 5 && $(grep -c . <<<"$v6") -ge 3 ]] || { echo "Cloudflare IP lists look wrong; nothing changed." >&2; exit 1; }

previous=""
[[ -f "$TARGET" ]] && previous="$(cat "$TARGET")"
{
  echo "# Generated by 35-cloudflare-realip.sh on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit."
  while read -r range; do [[ -n "$range" ]] && echo "set_real_ip_from ${range};"; done <<<"$v4"$'\n'"$v6"
  echo "real_ip_header CF-Connecting-IP;"
} > "$TARGET"

if nginx -t; then
  systemctl reload nginx
  echo "Cloudflare real-IP ranges installed: $(grep -c set_real_ip_from "$TARGET")."
else
  if [[ -n "$previous" ]]; then printf '%s\n' "$previous" > "$TARGET"; else rm -f "$TARGET"; fi
  echo "nginx rejected the configuration; restored the previous state." >&2
  exit 1
fi
